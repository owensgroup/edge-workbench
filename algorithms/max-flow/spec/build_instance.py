# -*- coding: utf-8 -*-
"""Build instance.json from the tutorial's worked example.

    EDGE_TUTORIAL=~/Projects/edge-algorithms/_algorithms/maximum-flow.md \
      python3 build_instance.py > instance.json

The graph, the source, the sink and the extents come from the tutorial. The
palette comes from domain.json beside this file. Nothing about the problem is
written here, which is the point: the page runs the example the tutorial
describes, and if the tutorial's example changes the page follows.

instance.json is committed rather than built during `npm run build`, for the
same reason the IR program is vendored -- a clean clone must build with node
and Python and no sibling checkout. `tests/test_instance_from_tutorial.py`
re-runs this and fails if the committed copy has drifted.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent.parent))

from edge_workbench import tutorial  # noqa: E402

DEFAULT = Path.home() / "Projects/edge-algorithms/_algorithms/maximum-flow.md"


def main() -> None:
    md = Path(os.environ.get("EDGE_TUTORIAL", DEFAULT))
    if not md.exists():
        sys.exit(
            f"no tutorial at {md}\n"
            f"  Set EDGE_TUTORIAL to the algorithm's .md file. The worked "
            f"example in it is the instance; there is no fallback, because a "
            f"hardcoded graph is the thing this replaced."
        )
    example = tutorial.read_example(md)
    domain = json.loads((HERE / "domain.json").read_text())
    domain.pop("_comment", None)
    domain.setdefault("progress", {})["coord"] = str(example["sink"])

    instance = tutorial.to_instance(example, domain=domain)
    instance["_comment"] = [
        "GENERATED by build_instance.py from the tutorial's worked example.",
        f"Source: {md.name}, `working_example_data`.",
        "Do not edit: regenerate. tests/test_instance_from_tutorial.py fails",
        "if this has drifted from the tutorial.",
        "",
        "The answer this instance is checked against is the tutorial's own",
        "`expect` block, not a number written in this repository.",
    ]
    json.dump(instance, sys.stdout, indent=1)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()

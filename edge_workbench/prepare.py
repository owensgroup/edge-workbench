# -*- coding: utf-8 -*-
"""Turn a tutorial into the artifacts the build needs, once, before publishing.

WHY A SEPARATE STEP
-------------------
The build used to read the tutorial live: meanings, tensor descriptions and
the published answer all came out of the `.md` while the page was being
written. That made the build depend on which branch a sibling repository
happened to have checked out -- and it showed, the moment work moved to a
branch that predated the tutorial's last edit. The build degraded to generic
captions and three oracle gates failed, for no reason to do with the
algorithm.

So the reading happens once, here, and what the build consumes is a committed
artifact. The build becomes hermetic: node, Python, and files in this
repository. That is also what makes it safe to run in CI without a network,
and what will make it safe to let a model fill the gaps -- a model in the
build path would make a page that changes when nothing changed.

WHAT THIS HALF DOES, AND DOES NOT
---------------------------------
Everything derivable without asking anything. It reads what the tutorial
already states and writes it out; where the tutorial states nothing, it says
so rather than inventing. The gaps it reports -- per-Einsum meanings that
only exist as phase-grouped prose, a worked example stated only in LaTeX --
are the input to the model-assisted half, which runs after this and fills
them.

PROVENANCE IS THE POINT
-----------------------
Every artifact records the tutorial it came from AND that tutorial's git SHA.
That buys three things a path alone does not:

  * a drift gate can compare against the tutorial AT THAT COMMIT, so it is
    reproducible and does not care which branch is checked out;
  * comparing the recorded SHA against the tutorial's head answers "has the
    tutorial moved since this was prepared?", which is the signal that tells
    an author to re-run this;
  * a reviewer can see which parts came from the author and which were
    derived, and spend their attention accordingly.
"""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from edge_workbench import tutorial as tut

ARTIFACT = "authored.json"


# --------------------------------------------------------------- source ---

def _git(repo: Path, *args: str) -> str | None:
    try:
        out = subprocess.run(["git", "-C", str(repo), *args],
                             capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def source_record(md: Path) -> dict:
    """Where this tutorial is, and exactly which version was read.

    `sha` is the last commit that touched the file, not the repository head:
    a tutorial that has not changed should not look stale because something
    else in the repo did.

    `dirty` matters more than it looks. Preparing from an uncommitted edit is
    legitimate while iterating, but the resulting artifact cannot be checked
    against anything, so it is recorded rather than hidden.
    """
    md = Path(md).resolve()
    repo = md.parent
    while repo != repo.parent and not (repo / ".git").exists():
        repo = repo.parent
    known_repo = (repo / ".git").exists()

    rel = str(md.relative_to(repo)) if known_repo else md.name
    sha = _git(repo, "log", "-1", "--format=%H", "--", rel) if known_repo else None
    status = _git(repo, "status", "--porcelain", "--", rel) if known_repo else None

    return {
        "tutorial": rel,
        "repo": repo.name if known_repo else None,
        "sha": sha or None,
        "dirty": bool(status),
        "preparedOn": date.today().isoformat(),
    }


# ---------------------------------------------------------------- gaps ----

@dataclass
class Prepared:
    """What was read, and what could not be."""

    source: dict
    example: dict | None = None
    meanings: dict = field(default_factory=dict)
    tensor_notes: dict = field(default_factory=dict)
    gaps: list[str] = field(default_factory=list)

    def to_artifact(self) -> dict:
        return {
            "_comment": [
                "GENERATED by `python3 -m edge_workbench.prepare`. Do not edit:",
                "re-run it. This is what the build reads instead of the",
                "tutorial, so that a build depends on files in this repository",
                "and not on which branch a sibling checkout happens to be on.",
                "",
                "`source.sha` is the commit the tutorial was read at. A gate",
                "compares it against the tutorial's head to tell you when the",
                "tutorial has moved and this needs re-running.",
                "",
                "`gaps` lists what the tutorial does not state in a form this",
                "step can read. Those are the model-assisted half's input; an",
                "empty list means the tutorial said everything itself.",
            ],
            "source": self.source,
            # Who wrote each field. Everything this half produces came from
            # the tutorial, so it is all the author's; the model-assisted half
            # marks what it fills. A reviewer reads model prose differently
            # from an author's, and cannot do that without being told which
            # is which.
            "provenance": {
                field: "author" for field, value in (
                    ("example", self.example),
                    ("meanings", self.meanings),
                    ("tensorNotes", self.tensor_notes),
                ) if value
            },
            "example": self.example,
            "meanings": self.meanings,
            "tensorNotes": self.tensor_notes,
            "gaps": self.gaps,
        }


def read_tutorial(md: Path) -> Prepared:
    """Everything the tutorial states in a form that can be read directly."""
    md = Path(md)
    out = Prepared(source=source_record(md))

    try:
        out.example = tut.read_example(md)
    except tut.TutorialError:
        out.example = None
        out.gaps.append(
            "example: no `working_example_data` block. The worked example is "
            "prose only, so nothing can run it or check an answer against it."
        )

    out.meanings = tut.read_meanings(md)
    if not out.meanings:
        out.gaps.append(
            "meanings: no `einsum_meanings` block. The walkthrough is grouped "
            "by phase, so there is no per-Einsum sentence to show beside a step."
        )

    out.tensor_notes = tut.read_all_tensor_notes(md)
    if not out.tensor_notes:
        out.gaps.append(
            "tensorNotes: neither `problem_statement` rows nor a "
            "`tensor_notes` block could be read."
        )
    return out


def write(md: Path, spec_dir: Path) -> Prepared:
    """Read the tutorial and write `<spec>/authored.json`."""
    prepared = read_tutorial(md)
    spec_dir = Path(spec_dir)
    if not spec_dir.is_dir():
        raise FileNotFoundError(
            f"no spec directory at {spec_dir}; prepare writes into an "
            f"algorithm that already exists"
        )
    target = spec_dir / ARTIFACT
    target.write_text(json.dumps(prepared.to_artifact(), indent=1,
                                 ensure_ascii=False) + "\n")
    return prepared


def load(spec_dir: Path) -> dict:
    """The prepared artifact, or {} when the algorithm has none yet."""
    path = Path(spec_dir) / ARTIFACT
    if not path.exists():
        return {}
    return json.loads(path.read_text())


# ----------------------------------------------------------------- cli ----

def main(argv: list[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        prog="edge_workbench.prepare",
        description="Read a tutorial into the artifacts the build consumes.",
    )
    ap.add_argument("tutorial", type=Path)
    ap.add_argument("--spec", type=Path, required=True,
                    help="the algorithm's spec/ directory")
    args = ap.parse_args(argv)

    if not args.tutorial.exists():
        print(f"no tutorial at {args.tutorial}")
        return 1

    prepared = write(args.tutorial, args.spec)
    src = prepared.source
    print(f"read {src['tutorial']} @ {(src['sha'] or 'unknown')[:12]}"
          + ("  (WORKING TREE IS DIRTY)" if src["dirty"] else ""))
    print(f"  example    : {'yes' if prepared.example else 'MISSING'}")
    print(f"  meanings   : {len(prepared.meanings)}")
    print(f"  tensorNotes: {len(prepared.tensor_notes)}")
    if prepared.gaps:
        print(f"\n{len(prepared.gaps)} gap(s) for the model-assisted step:")
        for gap in prepared.gaps:
            print(f"  - {gap}")
    else:
        print("\nno gaps: the tutorial states everything this step reads.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
